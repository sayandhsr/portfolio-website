export const drawPixelText = (ctx, text, x, y, color = '#0f380f', scale = 1) => {
  const upper = String(text).toUpperCase();
  let cursorX = Math.floor(x);
  const startY = Math.floor(y);

  for (let i = 0; i < upper.length; i++) {
    const ch = upper[i];
    if (ch === '\n') {
      cursorX = Math.floor(x);
      y += 7 * scale;
      continue;
    }

    const glyph = GLYPHS[ch] || GLYPHS['?'];
    const charWidth = glyph[0].length;

    ctx.fillStyle = color;
    for (let r = 0; r < glyph.length; r++) {
      const row = glyph[r];
      for (let c = 0; c < row.length; c++) {
        if (row[c] === '1') {
          ctx.fillRect(
            cursorX + c * scale,
            startY + r * scale,
            scale,
            scale
          );
        }
      }
    }

    cursorX += (charWidth + 1) * scale;
  }
  return cursorX;
};

export const measurePixelText = (text, scale = 1) => {
  const upper = String(text).toUpperCase();
  let totalWidth = 0;
  for (let i = 0; i < upper.length; i++) {
    const ch = upper[i];
    const glyph = GLYPHS[ch] || GLYPHS['?'];
    totalWidth += (glyph[0].length + 1) * scale;
  }
  return Math.max(0, totalWidth - 1 * scale);
};
